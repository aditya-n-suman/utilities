"""Generate src/engine/youtube/combining.ts: code points with a non-zero canonical combining class.

Python's matcher drops these after NFKD (unicodedata.combining(c) != 0); JavaScript has no API for
it, so we ship the table. Run with any Python 3.11+: python3 scripts/gen_combining.py
"""
import sys
import unicodedata
from pathlib import Path

points = [c for c in range(0x110000) if unicodedata.combining(chr(c))]
ranges, start, prev = [], points[0], points[0]
for c in points[1:]:
    if c != prev + 1:
        ranges.append((start, prev))
        start = c
    prev = c
ranges.append((start, prev))

body = ",".join(f"0x{a:x},0x{b:x}" for a, b in ranges)
out = Path(__file__).resolve().parent.parent / "src/engine/youtube/combining.ts"
out.write_text(
    "// GENERATED by scripts/gen_combining.py from Python's unicodedata "
    f"{unicodedata.unidata_version} (Python {sys.version.split()[0]}). Do not edit.\n"
    "// Inclusive [start, end] pairs of code points whose canonical combining class is non-zero.\n"
    f"const RANGES = [{body}];\n\n"
    "export function hasCombiningClass(codePoint: number): boolean {\n"
    "  let lo = 0, hi = RANGES.length / 2 - 1;\n"
    "  while (lo <= hi) {\n"
    "    const mid = (lo + hi) >> 1;\n"
    "    if (codePoint < RANGES[mid * 2]!) hi = mid - 1;\n"
    "    else if (codePoint > RANGES[mid * 2 + 1]!) lo = mid + 1;\n"
    "    else return true;\n"
    "  }\n"
    "  return false;\n"
    "}\n"
)
print(f"{len(points)} code points in {len(ranges)} ranges -> {out}")
